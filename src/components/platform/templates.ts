import type { DesignCategory } from "./DesignTypeModal";

export interface Template {
  id: string;
  name: string;
  category: DesignCategory;
  thumbnailUrl: string;
  canvasWidth: number;
  canvasHeight: number;
  elements: TemplateElement[];
}

export interface TemplateElement {
  id: string;
  type: "text" | "shape" | "image";
  x: number;
  y: number;
  width: number;
  height: number;
  content?: string;
  fontSize?: number;
  fontWeight?: string;
  color?: string;
  backgroundColor?: string;
  borderRadius?: number;
  opacity?: number;
  gradient?: string; // CSS linear-gradient or radial-gradient string
  shadow?: string; // e.g. "0 4px 20px rgba(0,0,0,0.3)"
  strokeColor?: string;
  strokeWidth?: number;
  textAlign?: "left" | "center" | "right";
  letterSpacing?: number;
  lineHeight?: number;
  fontFamily?: string;
}

// Helper to create templates faster
const t = (id: string, name: string, category: DesignCategory, w: number, h: number, elements: TemplateElement[]): Template => ({
  id, name, category, thumbnailUrl: "", canvasWidth: w, canvasHeight: h, elements,
});
const bg = (w: number, h: number, color: string, gradient?: string): TemplateElement => ({ id: "bg", type: "shape", x: 0, y: 0, width: w, height: h, backgroundColor: color, gradient });
const txt = (id: string, x: number, y: number, w: number, h: number, content: string, fontSize: number, color: string, fontWeight = "normal", opts?: Partial<TemplateElement>): TemplateElement => ({ id, type: "text", x, y, width: w, height: h, content, fontSize, fontWeight, color, ...opts });
const shp = (id: string, x: number, y: number, w: number, h: number, bgColor: string, br = 0, opts?: Partial<TemplateElement>): TemplateElement => ({ id, type: "shape", x, y, width: w, height: h, backgroundColor: bgColor, borderRadius: br, ...opts });

